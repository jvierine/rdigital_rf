use hdf5::{types::FixedAscii, File};
use rdigital_rf::metadata::{Numeric, Reader};

fn fixture(root: &std::path::Path) {
    let h = File::create(root.join("dmd_properties.h5")).unwrap();
    for (key, value) in [
        ("sample_rate_numerator", 1_000_000u64),
        ("sample_rate_denominator", 1),
        ("file_cadence_secs", 60),
        ("subdir_cadence_secs", 3600),
    ] {
        h.new_attr::<u64>()
            .create(key)
            .unwrap()
            .write_scalar(&value)
            .unwrap();
    }
    h.new_attr::<FixedAscii<2>>()
        .create("file_name")
        .unwrap()
        .write_scalar(&FixedAscii::<2>::from_ascii("mf").unwrap())
        .unwrap();
    for (directory, file, index) in [
        ("1970-01-01T00-00-00", 3540, 3_599_999_999u64),
        ("1970-01-01T01-00-00", 3600, 3_600_000_001),
    ] {
        let p = root.join(directory);
        std::fs::create_dir_all(&p).unwrap();
        let f = File::create(p.join(format!("mf@{file}.h5"))).unwrap();
        let g = f.create_group(&index.to_string()).unwrap();
        g.new_dataset::<i64>()
            .shape([2])
            .create("tx_idxs")
            .unwrap()
            .write_raw(&[9_007_199_254_740_993i64, index as i64])
            .unwrap();
        g.new_dataset::<f32>()
            .shape([1, 2])
            .create("max_snr")
            .unwrap()
            .write_raw(&[2.5f32, 9.0])
            .unwrap();
    }
}
#[test]
fn bounded_numeric_read_preserves_dtype_shape_indices_and_gaps() {
    let d = tempfile::tempdir().unwrap();
    fixture(d.path());
    // A broken unrelated file must never be visited.
    std::fs::write(d.path().join("1970-01-01T01-00-00/mf@3660.h5"), b"broken").unwrap();
    let r = Reader::open(d.path()).unwrap();
    let data = r
        .read(3_599_999_999..3_600_000_002, &["tx_idxs", "max_snr"])
        .unwrap();
    assert_eq!(data.len(), 2);
    assert_eq!(data[&3_599_999_999]["max_snr"].shape, vec![1, 2]);
    assert_eq!(
        data[&3_599_999_999]["max_snr"].values,
        Numeric::F32(vec![2.5, 9.0])
    );
    assert_eq!(
        data[&3_599_999_999]["tx_idxs"].values,
        Numeric::I64(vec![9_007_199_254_740_993, 3_599_999_999])
    );
    assert_eq!(
        r.read(3_599_999_999..3_600_000_001, &["max_snr"])
            .unwrap()
            .len(),
        1
    );
    assert!(r.read(0..60_000_000, &["max_snr"]).unwrap().is_empty());
    assert!(r.read(3_599_999_999..3_600_000_002, &["absent"]).is_err());
    assert!(r.read(3_660_000_000..3_660_000_001, &["max_snr"]).is_err());
    assert!(r.read(0..u64::MAX, &["max_snr"]).is_err());
}

#[test]
fn rational_rate_and_large_keys_stay_exact() {
    for (n, d, keys) in [
        (3u64, 2u64, [5399u64, 5401u64]),
        (
            10_000_000_000_000,
            1,
            [35_999_999_999_999_999, 36_000_000_000_000_001],
        ),
    ] {
        let dir = tempfile::tempdir().unwrap();
        fixture(dir.path());
        let props = File::open_rw(dir.path().join("dmd_properties.h5")).unwrap();
        props
            .attr("sample_rate_numerator")
            .unwrap()
            .write_scalar(&n)
            .unwrap();
        props
            .attr("sample_rate_denominator")
            .unwrap()
            .write_scalar(&d)
            .unwrap();
        drop(props);
        for (path, old, new) in [
            ("1970-01-01T00-00-00/mf@3540.h5", 3_599_999_999u64, keys[0]),
            ("1970-01-01T01-00-00/mf@3600.h5", 3_600_000_001, keys[1]),
        ] {
            let h = File::open_rw(dir.path().join(path)).unwrap();
            h.relink(&old.to_string(), &new.to_string()).unwrap();
        }
        let reader = Reader::open(dir.path()).unwrap();
        let data = reader.read(keys[0]..keys[1] + 1, &["max_snr"]).unwrap();
        assert_eq!(data.keys().copied().collect::<Vec<_>>(), keys);
        assert_eq!(
            reader.read(keys[0]..keys[1], &["max_snr"]).unwrap().len(),
            1
        );
    }
}

// Run explicitly with the upstream writer fixture generated by
// tests/compare_metadata.py; ordinary cargo tests do not require Python.
#[test]
#[ignore]
fn upstream_writer_fixture() {
    let root = std::env::var("DIGITAL_METADATA_FIXTURE").unwrap();
    let r = Reader::open(root).unwrap();
    let start = 1_700_003_599_000_000;
    let data = r
        .read(
            start..start + 2_000_001,
            &["tx_idxs", "max_snr", "beam", "scalar"],
        )
        .unwrap();
    assert_eq!(data.len(), 2);
    for (i, record) in data.values().enumerate() {
        assert_eq!(
            record["tx_idxs"].values,
            Numeric::I64(vec![
                9_007_199_254_740_993,
                start as i64 + i as i64 * 2_000_000
            ])
        );
        assert_eq!(record["max_snr"].shape, vec![2]);
        assert_eq!(record["max_snr"].values, Numeric::F32(vec![2.5, 9.0]));
        assert_eq!(record["beam"].values, Numeric::I8(vec![0, 4]));
        assert_eq!(record["scalar"].shape, Vec::<usize>::new());
        assert_eq!(record["scalar"].values, Numeric::F64(vec![3.25]));
    }
}
